import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { execFile } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { promisify } from 'node:util';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const production = process.env.PRODUCTION_REPO ?? '/srv/travel-journal/app';
const envFile = process.env.ENV_FILE ?? join(production, '.env.production');
const env = Object.fromEntries((await readFile(envFile, 'utf8')).split('\n').filter(line => /^[A-Z_]+=/.test(line)).map(line => { const at = line.indexOf('='); return [line.slice(0, at), line.slice(at + 1)]; }));
const origin = env.APP_ORIGIN;
const password = (await readFile(join(production, '.data/deploy/admin-password'), 'utf8')).trim();
const { chromium } = await import(pathToFileURL(join(repo, '.data/deployment-check/node_modules/playwright/index.mjs')).href);
const output = join(repo, '.data/deploy/checks');
await mkdir(output, { recursive: true, mode: 0o700 });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE, headless: true, args: ['--no-sandbox'] });
const admin = await browser.newContext({ baseURL: origin, reducedMotion: 'reduce', viewport: { width: 1440, height: 1000 } });
const anonymous = await browser.newContext({ baseURL: origin, reducedMotion: 'reduce', viewport: { width: 390, height: 844 } });
const page = await admin.newPage();
const publicPage = await anonymous.newPage();
page.setDefaultTimeout(30000);
const slug = `deployment-check-${Date.now().toString(36)}-${randomBytes(3).toString('hex')}`;
let journeyId;
let submitted = false;
const checks = [];
const passed = name => { checks.push(name); console.log(`PASS ${name}`); };
try {
  assert.equal((await anonymous.request.get('/api/health')).status(), 200);
  assert.equal((await anonymous.request.post(`/api/uploads?journeyId=00000000-0000-4000-8000-000000000001`, { headers: { Origin: origin } })).status(), 401);
  assert.equal((await anonymous.request.get('/api/media/00000000-0000-4000-8000-000000000001')).status(), 401);
  passed('HTTPS health and anonymous upload/original protection');
  await page.goto('/admin', { waitUntil: 'domcontentloaded' });
  assert.match(page.url(), /\/admin\/login$/);
  await page.getByLabel('账号', { exact: true }).fill('admin');
  await page.getByLabel('密码', { exact: true }).fill(password);
  await page.getByRole('button', { name: '登录管理页 →' }).click();
  await page.waitForURL(`${origin}/admin`);
  const sessionCookie = (await admin.cookies()).find(cookie => cookie.name === 'journal_session');
  assert.ok(sessionCookie?.secure && sessionCookie.httpOnly && sessionCookie.sameSite === 'Lax');
  passed('administrator login with Secure cookie');
  await page.getByRole('button', { name: '＋ 添加旅程', exact: true }).click();
  await page.getByLabel('目的地名称必填').fill('部署验证');
  await page.getByLabel('英文名称', { exact: true }).fill('DEPLOYMENT CHECK');
  await page.getByLabel('国家 / 地区', { exact: true }).fill('中国');
  await page.getByLabel('页面地址必填').fill(slug);
  await page.getByLabel('旅程标题必填').fill('图片存储验证');
  const today = new Date().toISOString().slice(0, 10);
  await page.getByLabel('开始日期必填').fill(today);
  await page.getByLabel('结束日期必填').fill(today);
  submitted = true;
  await page.getByRole('button', { name: '创建旅程草稿' }).click();
  await page.getByRole('status').filter({ hasText: '草稿已保存' }).waitFor();
  journeyId = (await page.locator('.admin-publish-row a').getAttribute('href')).split('/').at(-1);
  assert.equal((await anonymous.request.get(`/trips/${slug}`)).status(), 404);
  passed('draft saved and hidden from visitors');
  const denied = await admin.request.post(`/api/uploads?journeyId=${journeyId}`, { headers: { Origin: 'https://untrusted.example' }, multipart: { photos: { name: 'test.webp', mimeType: 'image/webp', buffer: await readFile(join(repo, 'assets/lisbon.webp')) } } });
  assert.equal(denied.status(), 403);
  const uploaded = page.waitForResponse(response => response.url().includes('/api/uploads?') && response.request().method() === 'POST');
  await page.getByLabel('添加照片', { exact: true }).setInputFiles(join(repo, 'assets/lisbon.webp'));
  const uploadResponse = await uploaded;
  assert.equal(uploadResponse.status(), 200);
  assert.equal((await uploadResponse.json()).results[0]?.ok, true);
  await page.getByRole('status').filter({ hasText: '上传处理完成' }).waitFor();
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.locator('.admin-trip-list button').filter({ hasText: '部署验证' }).click();
  await page.locator('.admin-photo').first().waitFor();
  assert.equal(await page.locator('.admin-photo').count(), 1);
  const image = await page.locator('.admin-photo img').getAttribute('src');
  assert.equal((await anonymous.request.get(image)).status(), 404);
  passed('real image upload persists; CSRF and draft media protection');
  await page.getByRole('button', { name: '发布旅程', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '已发布' }).waitFor();
  await publicPage.goto(`/trips/${slug}`, { waitUntil: 'domcontentloaded' });
  await publicPage.getByRole('heading', { name: '部署验证 · 图片存储验证' }).waitFor();
  const media = await anonymous.request.get(image);
  assert.equal(media.status(), 200);
  assert.match(media.headers()['content-type'], /image\/webp/);
  await page.screenshot({ path: join(output, 'admin-desktop.png'), fullPage: true });
  passed('published journey and processed WebP are publicly accessible');
  await page.getByRole('button', { name: '删除整段旅程', exact: true }).click();
  await page.getByRole('button', { name: '确认删除旅程' }).click();
  await page.getByRole('status').filter({ hasText: '整段旅程已移入' }).waitFor();
  assert.equal((await anonymous.request.get(image)).status(), 404);
  await page.getByRole('button', { name: '退出', exact: true }).click();
  await page.waitForURL(`${origin}/admin/login`);
  passed('deleted media blocked and administrator logout');
  await publicPage.goto('/', { waitUntil: 'domcontentloaded' });
  assert.ok(await publicPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await publicPage.screenshot({ path: join(output, 'site-mobile.png'), fullPage: true });
  passed('mobile homepage has no horizontal overflow');
} finally {
  await browser.close();
  if (submitted) {
    const args = ['compose', '--env-file', envFile, '-p', 'travel-journal', '-f', join(production, 'compose.yaml'), '-f', join(production, 'compose.vps.yaml'), 'run', '--rm', '-T', 'ops', 'npx', 'tsx', 'ops/cleanup-deployment-check.ts', slug];
    if (journeyId) args.push(journeyId);
    const result = await promisify(execFile)('docker', args, { timeout: 30000 });
    process.stdout.write(result.stdout);
  }
  await writeFile(join(output, 'result.json'), JSON.stringify({ origin, checks, temporaryContentRemoved: submitted }, null, 2) + '\n', { mode: 0o600 });
}
